/// <summary>The data-quality review: the rules find candidates, the model only picks and explains them.</summary>
public abstract class DataQualityReviewTests<TStartupModule> : AiFeatureTestBase<TStartupModule>
    where TStartupModule : IAbpModule
{
    private static AiDataQualityReviewInput Review(string scope = AiFeatureScopes.Team) =>
        new() { From = Day, To = Day.AddDays(1), Scope = scope, TimeZone = "UTC" };

    /// <summary>The caller's device clock 15 minutes off (C1, a notice) and three of Ayesha's blocks with software input
    /// (C2, info).</summary>
    private async Task SeedCandidatesAsync()
    {
        await InsertBlockAsync(CallerId, WebsiteId, Day.AddHours(15), 10, clockSkew: 900);
        for (var i = 0; i < 3; i++)
        {
            await InsertBlockAsync(AyeshaId, WebsiteId, Day.AddHours(14).AddMinutes(15 * i), 10, injected: 2);
        }
    }

    private static object Item(string candidateId, string explanation, string actionId = "", params string[] reasons) => new
    {
        candidateId,
        title = "Worth a look",
        explanation,
        possibleReasons = reasons,
        actionId
    };

    [Fact]
    public async Task The_Model_Should_Only_Explain_Known_Candidates_With_Their_Allowed_Actions()
    {
        await ReadyAsync();
        await SeedCandidatesAsync();
        Model.EnqueueJson(Json(new
        {
            items = new[]
            {
                Item("C1", "A device used by {ME} reported a clock difference of up to {F1}.", "sync-device-clock", "The clock is set by hand"),
                Item("C9", "Something the rules never found."),
                Item("C2", "Some blocks tracked by {M1} had input generated by software.", "open-team"),
                Item("C1", "The same candidate again.")
            }
        }));

        var result = await Ai.CreateDataQualityReviewAsync(Review());

        result.Meta.Status.ShouldBe(AiResultStatuses.Generated);
        result.CandidateCount.ShouldBe(2);
        result.Items.Select(i => i.CandidateId).ShouldBe(new[] { "C1", "C2" });

        var clock = result.Items[0];
        clock.Kind.ShouldBe(AiDataQualityKinds.ClockSkew);
        clock.Severity.ShouldBe(AiDataQualitySeverities.Notice);
        clock.Explanation.ShouldBe("A device used by you reported a clock difference of up to 15 min.");
        clock.ActionId.ShouldBe("sync-device-clock");
        clock.ActionRouteId.ShouldBeNull();
        clock.SubjectName.ShouldBe("you");
        clock.SubjectUserId.ShouldBe(CallerId);
        clock.PossibleReasons.ShouldBe(new[] { "The clock is set by hand" });
        clock.Facts.Select(f => (f.Label, f.Display)).ShouldBe(new[]
        {
            ("largest device clock difference (you)", "15 min"), ("clock difference threshold (you)", "5 min")
        });

        var software = result.Items[1];
        software.Kind.ShouldBe(AiDataQualityKinds.SoftwareInput);
        software.SubjectName.ShouldBe(AyeshaName);
        software.SubjectUserId.ShouldBe(AyeshaId);
        software.ActionId.ShouldBeNull("open-team is not an action of a software-input candidate");
        software.Explanation.ShouldBe("Some blocks tracked by " + AyeshaName + " had input generated by software.");

        var call = Model.Calls.ShouldHaveSingleItem();
        ShouldHoldNothingPrivate(call);
        call.AllText.ShouldContain("\"allowedActions\":[\"sync-device-clock\"]");
    }

    [Fact]
    public async Task No_Candidates_Should_Mean_No_Call()
    {
        await ReadyAsync();

        var result = await Ai.CreateDataQualityReviewAsync(Review());

        result.Meta.Status.ShouldBe(AiResultStatuses.NoData);
        result.Items.ShouldBeEmpty();
        Model.Calls.ShouldBeEmpty();
    }

    [Fact]
    public async Task A_Provider_Failure_Should_List_One_Templated_Item_Per_Candidate_Notices_First()
    {
        await ReadyAsync();
        await SeedCandidatesAsync();
        Model.EnqueueThrow(new AiProviderException(AiProviderErrorKind.Timeout, 408));

        var result = await Ai.CreateDataQualityReviewAsync(Review());

        result.Meta.Status.ShouldBe(AiResultStatuses.Fallback);
        result.Items.Select(i => i.Kind).ShouldBe(new[] { AiDataQualityKinds.ClockSkew, AiDataQualityKinds.SoftwareInput });
        result.Items[0].Explanation.ShouldBe("A device used by you reported a clock difference of up to 15 min.");
        result.Items[0].ActionId.ShouldBe(DataQualityRules.SyncDeviceClock);
        result.Items[1].Explanation.ShouldBe("3 blocks tracked by " + AyeshaName + " had input generated by software.");
        result.Items[1].PossibleReasons.ShouldContain("Remote desktop");
        result.Items.ShouldAllBe(i => i.Facts.Count > 0);
    }

    [Fact]
    public async Task Judging_Or_Numeric_Text_Should_Be_Repaired_And_Then_Replaced()
    {
        await ReadyAsync();
        await SeedCandidatesAsync();
        var bad = Json(new { items = new[] { Item("C2", "{M1} may be faking input on 3 blocks.") } });
        Model.EnqueueJson(bad).EnqueueJson(bad);

        var result = await Ai.CreateDataQualityReviewAsync(Review());

        Model.Calls.Count.ShouldBe(2);
        result.Meta.Status.ShouldBe(AiResultStatuses.Fallback);
        result.Items.ShouldAllBe(i => !i.Explanation.Contains("faking"));
    }

    [Fact]
    public async Task Unknown_Kinds_Should_Be_Refused()
    {
        await ReadyAsync();

        await Should.ThrowAsync<AbpValidationException>(() => Ai.CreateDataQualityReviewAsync(
            new AiDataQualityReviewInput { From = Day, To = Day.AddDays(1), Scope = AiFeatureScopes.Team, Kinds = new() { "low-activity" } }));
        Model.Calls.ShouldBeEmpty();
    }

    [Fact]
    public void Kinds_Should_Default_By_Scope()
    {
        DataQualityReviewFeature.ResolveKinds(null, team: true).ShouldBe(AiDataQualityKinds.All);
        DataQualityReviewFeature.ResolveKinds(new string[0], team: false).ShouldBe(AiDataQualityKinds.Self);
        DataQualityReviewFeature.ResolveKinds(new[] { " data-gap ", "data-gap" }, team: false).ShouldBe(new[] { "data-gap" });
        Should.Throw<AbpValidationException>(() => DataQualityReviewFeature.ResolveKinds(new[] { AiDataQualityKinds.NeverTracked }, team: false));
    }
}

/// <summary>A worker: their own review only.</summary>
public abstract class DataQualityReviewWorkerTests<TStartupModule> : AiFeatureTestBase<TStartupModule>
    where TStartupModule : IAbpModule
{
    protected override string CallerRole => WorkspaceRoles.Member;

    protected override void AfterAddApplication(IServiceCollection services)
    {
        base.AfterAddApplication(services);
        services.DenyPermissions(TrackerPermissions.Activities.ViewAll, TrackerPermissions.Reporting.Default, TrackerPermissions.Team.Manage);
    }

    [Fact]
    public async Task The_Team_Should_Be_Refused_And_Their_Own_Data_Reviewed()
    {
        await ReadyAsync();
        await InsertBlockAsync(CallerId, WebsiteId, Day.AddHours(15), 10, clockSkew: 900);
        for (var i = 0; i < 3; i++)
        {
            await InsertBlockAsync(AyeshaId, WebsiteId, Day.AddHours(14).AddMinutes(15 * i), 10, injected: 2);
        }

        await Should.ThrowAsync<AbpAuthorizationException>(() => Ai.CreateDataQualityReviewAsync(
            new AiDataQualityReviewInput { From = Day, To = Day.AddDays(1), Scope = AiFeatureScopes.Team }));
        await Should.ThrowAsync<AbpValidationException>(() => Ai.CreateDataQualityReviewAsync(new AiDataQualityReviewInput
        {
            From = Day, To = Day.AddDays(1), Scope = AiFeatureScopes.Self, Kinds = new() { AiDataQualityKinds.OutdatedAgent }
        }));
        Model.Calls.ShouldBeEmpty();

        Model.EnqueueJson(Json(new
        {
            items = new[] { new { candidateId = "C1", title = "Clock off", explanation = "A device used by {ME} is off by {F1}.", possibleReasons = new string[0], actionId = "" } }
        }));
        var mine = await Ai.CreateDataQualityReviewAsync(new AiDataQualityReviewInput { From = Day, To = Day.AddDays(1), Scope = AiFeatureScopes.Self });

        // Only the caller's own candidate: Ayesha's software input is not theirs to see.
        mine.CandidateCount.ShouldBe(1);
        var item = mine.Items.ShouldHaveSingleItem();
        item.Kind.ShouldBe(AiDataQualityKinds.ClockSkew);
        item.SubjectName.ShouldBe("you");
        ShouldHoldNothingPrivate(Model.Calls.ShouldHaveSingleItem());
    }
}
