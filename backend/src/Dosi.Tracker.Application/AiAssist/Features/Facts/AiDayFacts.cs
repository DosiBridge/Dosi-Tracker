using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json.Nodes;
using Dosi.Tracker.AiAssist.Context;
using Dosi.Tracker.AiAssist.Read;
using Dosi.Tracker.Reporting;

namespace Dosi.Tracker.AiAssist.Features.Facts;

/// <summary>
/// Turns one member's local day into bundle facts and lists (spec 11, member-day-summary): when the day started and
/// ended, the longest continuous stretch (gaps of <see cref="MergeGapMinutes"/> or less merged), the breaks longer than
/// <see cref="BreakThresholdMinutes"/>, how blocks ended, what share of the time had no activity measurement or
/// software-generated input, morning / afternoon / evening shares, the comparison with the previous week's active
/// days, and (only when the policy allowed them to be read) notes and window titles. Totals, projects and apps come from
/// <see cref="AiPeriodFacts"/>.
/// </summary>
public static class AiDayFacts
{
    public const double MergeGapMinutes = 2;
    public const double BreakThresholdMinutes = 15;
    public const int MaxProjects = 6;
    public const int MaxApps = 8;
    public const int MaxNotes = 10;
    public const int MaxTitles = 10;

    /// <summary>Morning ends and afternoon starts at this local hour; evening starts at <see cref="EveningStartHour"/>.</summary>
    public const int AfternoonStartHour = 12;
    public const int EveningStartHour = 17;

    // Keys of the totals list (besides AiPeriodFacts').
    public const string Day = "day";
    public const string FirstStart = "firstStart";
    public const string LastEnd = "lastEnd";
    public const string LongestSpan = "longestSpan";
    public const string LongestSpanStart = "longestSpanStart";
    public const string LongestSpanEnd = "longestSpanEnd";
    public const string BreakThreshold = "breakThreshold";
    public const string Breaks = "breaks";
    public const string BreakTime = "breakTime";
    public const string SoftwareInputBlocks = "softwareInputBlocks";
    public const string WeekActiveDays = "previousWeekActiveDays";
    public const string WeekAverage = "previousWeekAverage";
    public const string WeekDelta = "changeFromPreviousWeekAverage";

    public const string EndReasonsList = "endReasons";
    public const string DayPartsList = "dayParts";
    public const string NotesList = "notes";
    public const string TitlesList = "windowTitles";

    public const string SoftwareInputCaveat =
        "Some blocks had input generated by software, for example by remote desktop, accessibility or automation tools.";

    /// <summary>The day and its zone.</summary>
    public static void AddDay(AiBundleWriter writer, JsonObject totals, DateTime localDate, TimeZoneInfo zone, DateTime fromUtc, DateTime nowUtc)
    {
        var today = AiPeriodFacts.Today(zone, nowUtc);
        totals[Day] = writer.AddFact("day", DisplayFormat.Day(localDate, DisplayFormat.NeedsYear(localDate, localDate, today)));
        totals[AiPeriodFacts.TimeZone] = writer.AddFact("time zone", DisplayFormat.Zone(zone, fromUtc));
        if (localDate.Date == today)
        {
            writer.AddCaveat("The day is today, so its figures may still change.");
        }
    }

    /// <summary>First start, last end, the longest continuous stretch and the breaks between stretches.</summary>
    public static void AddRhythm(AiBundleWriter writer, JsonObject totals, IReadOnlyList<AiBlock> blocks, TimeZoneInfo zone, string? subject)
    {
        if (blocks.Count == 0)
        {
            return;
        }

        var spans = Spans(blocks);
        totals[FirstStart] = writer.AddFact("first start", DisplayFormat.LocalTime(spans[0].Start, zone), subject);
        totals[LastEnd] = writer.AddFact("last end", DisplayFormat.LocalTime(spans.Max(s => s.End), zone), subject);

        var longest = spans.OrderByDescending(s => s.End - s.Start).ThenBy(s => s.Start).First();
        totals[LongestSpan] = writer.AddFact("longest continuous stretch", DisplayFormat.Duration((longest.End - longest.Start).TotalMinutes), subject);
        totals[LongestSpanStart] = writer.AddFact("start of the longest stretch", DisplayFormat.LocalTime(longest.Start, zone), subject);
        totals[LongestSpanEnd] = writer.AddFact("end of the longest stretch", DisplayFormat.LocalTime(longest.End, zone), subject);

        var breaks = spans.Zip(spans.Skip(1), (a, b) => (b.Start - a.End).TotalMinutes)
            .Where(gap => gap > BreakThresholdMinutes)
            .ToList();
        totals[BreakThreshold] = writer.AddFact("break threshold", DisplayFormat.Duration(BreakThresholdMinutes));
        totals[Breaks] = writer.AddFact("breaks longer than the break threshold", AiPeriodFacts.Count(breaks.Count), subject);
        if (breaks.Count > 0)
        {
            totals[BreakTime] = writer.AddFact("time in those breaks", DisplayFormat.Duration(breaks.Sum()), subject);
        }
    }

    /// <summary>How many blocks ended for each (known) reason.</summary>
    public static void AddEndReasons(AiBundleWriter writer, IReadOnlyList<AiBlock> blocks)
    {
        var reasons = new JsonObject();
        foreach (var group in blocks.Where(b => !string.IsNullOrEmpty(b.EndReason)).GroupBy(b => b.EndReason!).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            // End reasons are a fixed set of words (ActivityConsts.EndReasons); anything else was stored as null.
            reasons[group.Key] = writer.AddFact("blocks that ended for this reason", AiPeriodFacts.Count(group.Count()));
        }

        if (reasons.Count > 0)
        {
            writer.SetList(EndReasonsList, reasons);
        }
    }

    /// <summary>The share of time without activity measurement and the blocks with software-generated input, with their
    /// caveats.</summary>
    public static void AddMeasurement(AiBundleWriter writer, JsonObject totals, IReadOnlyList<AiBlock> blocks)
    {
        var minutes = blocks.Sum(b => b.Minutes);
        var unmeasured = blocks.Where(b => b.Productivity == null).Sum(b => b.Minutes);
        if (minutes > 0 && unmeasured > 0)
        {
            totals[AiPeriodFacts.UnmeasuredShare] = writer.AddFact("share of tracked time without activity measurement",
                AiPeriodFacts.Share(unmeasured, minutes));
            writer.AddCaveat(AiPeriodFacts.UnmeasuredCaveat);
        }

        var software = blocks.Count(b => b.InjectedInputEvents is > 0);
        if (software > 0)
        {
            totals[SoftwareInputBlocks] = writer.AddFact("blocks with software-generated input", AiPeriodFacts.Count(software));
            writer.AddCaveat(SoftwareInputCaveat);
        }
    }

    /// <summary>Morning, afternoon and evening shares of the tracked minutes of the hourly report.</summary>
    public static void AddDayParts(AiBundleWriter writer, IReadOnlyList<AiHourlyRow> hourly)
    {
        var total = hourly.Sum(h => h.TrackedMinutes);
        if (total <= 0)
        {
            return;
        }

        double Part(Func<int, bool> hours) => hourly.Where(h => hours(h.Hour)).Sum(h => h.TrackedMinutes);

        writer.SetList(DayPartsList, new JsonObject
        {
            ["morning"] = writer.AddFact("share of the tracked time before noon", AiPeriodFacts.Share(Part(h => h < AfternoonStartHour), total)),
            ["afternoon"] = writer.AddFact("share of the tracked time in the afternoon",
                AiPeriodFacts.Share(Part(h => h is >= AfternoonStartHour and < EveningStartHour), total)),
            ["evening"] = writer.AddFact("share of the tracked time in the evening", AiPeriodFacts.Share(Part(h => h >= EveningStartHour), total))
        });
    }

    /// <summary>The previous week's active days (days with tracked time) of the member, their average and how the day
    /// compares with it.</summary>
    public static void AddWeekComparison(
        AiBundleWriter writer, JsonObject totals, IReadOnlyList<AiMemberDayRow> previousWeek, Guid userId, double dayMinutes, string? subject)
    {
        var active = previousWeek.Where(d => d.UserId == userId && d.TrackedMinutes > 0).ToList();
        totals[WeekActiveDays] = writer.AddFact("days with tracked time in the previous week", AiPeriodFacts.Count(active.Count), subject);
        if (active.Count == 0)
        {
            return;
        }

        var average = active.Sum(d => d.TrackedMinutes) / active.Count;
        totals[WeekAverage] = writer.AddFact("average tracked time on those days", DisplayFormat.Duration(average), subject);
        totals[WeekDelta] = writer.AddFact("difference from that average", DisplayFormat.Delta(dayMinutes - average), subject);
    }

    /// <summary>The day's distinct notes (at most <see cref="MaxNotes"/>); blocks carry notes only when the policy
    /// allows them.</summary>
    public static void AddNotes(AiBundleWriter writer, IReadOnlyList<AiBlock> blocks)
    {
        var notes = new JsonArray();
        foreach (var note in blocks.Select(b => b.Note).Where(n => !string.IsNullOrWhiteSpace(n)).Distinct(StringComparer.Ordinal).Take(MaxNotes))
        {
            var id = writer.AddNote(note);
            if (!notes.Any(n => (string?)n == id))
            {
                notes.Add(id);
            }
        }

        if (notes.Count > 0)
        {
            writer.SetList(NotesList, notes);
        }
    }

    /// <summary>The window titles with the most focused time (at most <paramref name="max"/>), with their app; blocks
    /// carry titles only when the policy allows them.</summary>
    public static void AddTitles(AiBundleWriter writer, IReadOnlyList<AiBlock> blocks, int max = MaxTitles)
    {
        var titles = blocks
            .SelectMany(b => b.WindowTitles ?? Array.Empty<AiWindowTitle>())
            .GroupBy(t => (t.App, t.Title))
            .Select(g => (g.Key.App, g.Key.Title, Seconds: g.Sum(t => (long)(t.Seconds ?? 0))))
            .OrderByDescending(t => t.Seconds)
            .ThenBy(t => t.Title, StringComparer.Ordinal)
            .Take(Math.Max(0, max))
            .ToList();

        var list = new JsonArray();
        foreach (var (app, title, _) in titles)
        {
            list.Add(new JsonObject { ["title"] = writer.AddTitle(title), ["app"] = writer.AddApp(app) });
        }

        if (list.Count > 0)
        {
            writer.SetList(TitlesList, list);
        }
    }

    /// <summary>The blocks as continuous stretches: sorted by start, a gap of <see cref="MergeGapMinutes"/> or less
    /// (or an overlap) joins two blocks.</summary>
    public static IReadOnlyList<(DateTime Start, DateTime End)> Spans(IEnumerable<AiBlock> blocks)
    {
        var spans = new List<(DateTime Start, DateTime End)>();
        foreach (var block in blocks.OrderBy(b => b.StartedAt))
        {
            var start = ReportCalendar.AsUtc(block.StartedAt);
            var end = ReportCalendar.AsUtc(block.EndedAt);
            if (end < start)
            {
                end = start;
            }

            if (spans.Count > 0 && (start - spans[^1].End).TotalMinutes <= MergeGapMinutes)
            {
                spans[^1] = (spans[^1].Start, end > spans[^1].End ? end : spans[^1].End);
            }
            else
            {
                spans.Add((start, end));
            }
        }

        return spans;
    }
}
