using System;

namespace Dosi.Tracker.Reporting;

/// <summary>
/// How trustworthy one member's tracked data in the range is (<c>GET /api/app/reporting/data-quality</c>): signals the
/// agents record per block that no other report exposes. Describes the data, never the person.
/// </summary>
public class DataQualityRowDto
{
    public Guid UserId { get; set; }

    /// <summary>The member's user name; empty when the account no longer exists.</summary>
    public string UserName { get; set; } = string.Empty;

    /// <summary>Blocks that started in the range.</summary>
    public int Blocks { get; set; }

    public double TrackedMinutes { get; set; }

    /// <summary>Tracked minutes of blocks whose activity % was not measured (input tracking off for the project, or a
    /// session the agent could not read input in, such as Wayland).</summary>
    public double UnmeasuredMinutes { get; set; }

    /// <summary>The largest difference between the device clock and the server clock measured when a block was
    /// uploaded, in seconds and whichever its direction; null when no block's upload said when it was sent.</summary>
    public int? MaxAbsClockSkewSeconds { get; set; }

    /// <summary>Blocks during which the agent saw input generated by software (remote desktop, accessibility tools,
    /// automation) rather than by a physical device. Such input never counts towards activity.</summary>
    public int BlocksWithInjectedInput { get; set; }

    /// <summary>UTC instant the member's latest block in the range ended; null when there is none.</summary>
    public DateTime? LastActivityAt { get; set; }
}
